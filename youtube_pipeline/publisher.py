"""
YouTube Shorts Video Publisher via YouTube Data API v3.
"""

import os
import sys
import time
from pathlib import Path
from typing import Optional, List, Dict, Any

from googleapiclient.http import MediaFileUpload
from googleapiclient.errors import HttpError

from .auth import YouTubeAuthenticator
from .config import (
    DEFAULT_PRIVACY_STATUS,
    DEFAULT_CATEGORY_ID,
    DEFAULT_TAGS
)

class YouTubePublisher:
    """Handles video uploading, metadata insertion, and Shorts distribution."""

    def __init__(self):
        self.service = YouTubeAuthenticator.get_authenticated_service()

    def upload_short(
        self,
        video_path: Path,
        title: str,
        description: str = "",
        tags: Optional[List[str]] = None,
        privacy_status: str = DEFAULT_PRIVACY_STATUS,
        category_id: str = DEFAULT_CATEGORY_ID,
        notify_subscribers: bool = True
    ) -> Dict[str, Any]:
        """
        Uploads an MP4 video as a YouTube Short using resumable multipart chunking.
        Automatically tags the video with #Shorts for Shorts shelf indexing.
        """
        video_path = Path(video_path).resolve()
        if not video_path.exists():
            raise FileNotFoundError(f"Video file not found: {video_path}")

        file_size_mb = video_path.stat().st_size / (1024 * 1024)

        # Ensure #Shorts is present in title or description
        formatted_title = title.strip()
        if "#shorts" not in formatted_title.lower() and len(formatted_title) + 8 <= 100:
            formatted_title = f"{formatted_title} #Shorts"

        formatted_desc = description.strip()
        if "#shorts" not in formatted_desc.lower():
            formatted_desc = f"{formatted_desc}\n\n#Shorts #Viral #Reels #AI\nGenerated by AutoReelStudio"

        all_tags = list(set((tags or []) + DEFAULT_TAGS))

        body = {
            "snippet": {
                "title": formatted_title[:100],
                "description": formatted_desc[:5000],
                "tags": all_tags[:50],
                "categoryId": str(category_id)
            },
            "status": {
                "privacyStatus": privacy_status,
                "selfDeclaredMadeForKids": False
            }
        }

        print("\n" + "=" * 65)
        print("🎬 YOUTUBE DATA API v3 — SHORTS UPLOADER")
        print("=" * 65)
        print(f"📁 Video File:     {video_path.name} ({file_size_mb:.2f} MB)")
        print(f"📌 Title:          {formatted_title}")
        print(f"🔒 Privacy Status: {privacy_status.upper()}")
        print(f"🏷️ Category ID:    {category_id}")
        print("⚡ Ingesting into YouTube API via resumable binary chunks...")

        # 4MB chunk size for reliable uploads
        chunk_size = 4 * 1024 * 1024
        media = MediaFileUpload(
            str(video_path),
            mimetype="video/mp4",
            resumable=True,
            chunksize=chunk_size
        )

        request = self.service.videos().insert(
            part="snippet,status",
            body=body,
            media_body=media,
            notifySubscribers=notify_subscribers
        )

        response = None
        error = None
        retry = 0
        max_retries = 5

        while response is None:
            try:
                status, response = request.next_chunk()
                if status:
                    progress = int(status.progress() * 100)
                    print(f"  ⏳ Upload Progress: {progress}% uploaded...")
            except HttpError as e:
                if e.resp.status in [500, 502, 503, 504]:
                    retry += 1
                    if retry > max_retries:
                        raise e
                    sleep_secs = 2 ** retry
                    print(f"  ⚠️ Transient HTTP {e.resp.status}. Retrying in {sleep_secs}s...")
                    time.sleep(sleep_secs)
                else:
                    raise e

        video_id = response.get("id")
        shorts_url = f"https://youtube.com/shorts/{video_id}"
        watch_url = f"https://www.youtube.com/watch?v={video_id}"

        print("=" * 65)
        print(f"🎉 YOUTUBE SHORT PUBLISHED SUCCESSFULLY!")
        print(f"🆔 Video ID:       {video_id}")
        print(f"🔗 Shorts URL:     {shorts_url}")
        print(f"▶️ Watch URL:      {watch_url}")
        print("=" * 65)

        return {
            "success": True,
            "video_id": video_id,
            "shorts_url": shorts_url,
            "watch_url": watch_url,
            "title": formatted_title,
            "privacy_status": privacy_status,
            "file_size_mb": round(file_size_mb, 2)
        }
